#!/usr/bin/env bash
# Parse `make bootstrap-anvil` forge logs and write env files for local fork testing.
# Usage: write-fork-env.sh <forge-log> <evm-env-out> [web-env-out]
set -euo pipefail

LOG="${1:?usage: write-fork-env.sh <forge-log> <evm-env-out> [web-env-out]}"
EVM_OUT="${2:?missing evm env output path}"
WEB_OUT="${3:-}"
HOOK_MODE="${HOOK_MODE:-return-delta}"

FORK_RPC_URL="http://127.0.0.1:8545"
FORK_CHAIN_ID="84532"
ANVIL_DEFAULT_KEY="0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80"
TESTER_RECIPIENTS="0x9965507D1a55bcC2695C58ba16FB37d819B0A4dc,0x976EA74026E726554dB657fA54763abd0C3a0aa9,0x14dC79964da2C08b23698B3D3cc7Ca32193d9955,0x23618e81E3f5cdF7f54C3d65f7FBc0aBf5B21E8f,0xa0Ee7A142d267C1f36714E4a8F75612F20a79720"
TESTER_MUSDC_WHOLE="10000"

POOL_MANAGER="0x05E73354cFDd6745C338b50BcFDfA3Aa6fA03408"
POSITION_MANAGER="0x4b2c77d209d3405f41a037ec6c77f7f5b8e2ca80"
UNIVERSAL_ROUTER="0x492e6456d9528771018deb9e87ef7750ef184104"
POOL_SWAP_TEST="0x8B5bcC363ddE2614281aD875bad385E0A785D3B9"
POOL_MODIFY_LIQUIDITY_TEST="0x37429cD17Cb1454C34E7F50b09725202Fd533039"
PERMIT2="0x000000000022D473030F116dDEE9F6B43aC78BA3"

HOOK_LOG_KEY="PhoenixV4ReturnDeltaHook"
POOL_FEE="0"

if [[ "$HOOK_MODE" != "return-delta" ]]; then
  echo "write-fork-env: unsupported HOOK_MODE='$HOOK_MODE' (expected return-delta)" >&2
  exit 1
fi

pick() {
  local key="$1"
  awk -v k="$key" '
    /^== Logs ==/ { inlogs=1; next }
    inlogs && /^## / { exit }
    inlogs && index($0, "  " k ": ") == 1 {
      sub(/^  [^:]+: /, "")
      print
      exit
    }
  ' "$LOG"
}

PXT="$(pick PXT)"
MUSDC="$(pick mUSDC)"
HOOK="$(pick "$HOOK_LOG_KEY")"
COLLECTOR="$(pick PhoenixFeeCollector)"
DONATION="$(pick 'Donation wallet')"
MARKETING="$(pick 'Marketing wallet')"
NO_PENALTY="$(pick 'NoPenalty wallet')"
ADMIN="$(pick Admin)"
CURRENCY0="$(pick currency0)"
CURRENCY1="$(pick currency1)"
ANTI_BOT="$(pick 'Anti-bot seller')"
SELL_UNLOCK="$(pick 'Sell unlock timestamp')"
OPEN_SELL="$(pick PhoenixAntiBotOpenSell)"

REQUIRED=(PXT MUSDC HOOK DONATION MARKETING ADMIN CURRENCY0 CURRENCY1 COLLECTOR OPEN_SELL)

for v in "${REQUIRED[@]}"; do
  if [[ -z "${!v}" ]]; then
    echo "write-fork-env: missing ${v} in forge log (HOOK_MODE=$HOOK_MODE)" >&2
    exit 1
  fi
done

FEE_COLLECTOR_LINE=""
if [[ -n "${COLLECTOR:-}" ]]; then
  FEE_COLLECTOR_LINE="FEE_COLLECTOR=${COLLECTOR}"
fi

cat >"$EVM_OUT" <<EOF
# Auto-generated by make bootstrap-anvil (Base Sepolia fork)
EVM_CLUSTER=anvil
HOOK_MODE=${HOOK_MODE}
ANVIL_RPC_URL=${FORK_RPC_URL}
PRIVATE_KEY=${ANVIL_DEFAULT_KEY}
ADMIN_ADDRESS=${ADMIN}
DONATION_WALLET=${DONATION}
MARKETING_WALLET=${MARKETING}
NO_PENALTY_WALLET=${NO_PENALTY}
PXT_ADDRESS=${PXT}
QUOTE_TOKEN_ADDRESS=${MUSDC}
PHOENIX_HOOK=${HOOK}
${FEE_COLLECTOR_LINE}
POOL_CURRENCY0=${CURRENCY0}
POOL_CURRENCY1=${CURRENCY1}
POOL_FEE=${POOL_FEE}
POOL_TICK_SPACING=60
POOL_MANAGER=${POOL_MANAGER}
POSITION_MANAGER=${POSITION_MANAGER}
UNIVERSAL_ROUTER=${UNIVERSAL_ROUTER}
POOL_SWAP_TEST=${POOL_SWAP_TEST}
POOL_MODIFY_LIQUIDITY_TEST=${POOL_MODIFY_LIQUIDITY_TEST}
PERMIT2=${PERMIT2}
ANTI_BOT_SELLER=${ANTI_BOT:-$ADMIN}
ANTI_BOT_OPEN_SELL=${OPEN_SELL}
SELL_UNLOCK_TIMESTAMP=${SELL_UNLOCK}
USE_MOCK_USDC=true
QUOTE_DECIMALS=6

# Local testers
RECIPIENTS=${TESTER_RECIPIENTS}
AMOUNT_WHOLE=${TESTER_MUSDC_WHOLE}
FUND_ETH=true
EOF
echo "Wrote $EVM_OUT"

if [[ -n "$WEB_OUT" ]]; then
  FEE_COLLECTOR_WEB=""
  if [[ -n "${COLLECTOR:-}" ]]; then
    FEE_COLLECTOR_WEB="VITE_FEE_COLLECTOR=${COLLECTOR}"
  fi
  cat >"$WEB_OUT" <<EOF
# Auto-generated by make bootstrap-anvil
VITE_PXT_ADDRESS=${PXT}
VITE_QUOTE_TOKEN_ADDRESS=${MUSDC}
VITE_PHOENIX_HOOK=${HOOK}
${FEE_COLLECTOR_WEB}
VITE_ANTI_BOT_OPEN_SELL=${OPEN_SELL}
VITE_POOL_MANAGER=${POOL_MANAGER}
VITE_POOL_SWAP_TEST=${POOL_SWAP_TEST}
VITE_POOL_MODIFY_LIQUIDITY_TEST=${POOL_MODIFY_LIQUIDITY_TEST}
VITE_STATE_VIEW=0x571291b572ed32ce6751a2Cb2486EbEe8DEfB9B4
VITE_QUOTER=0x4A6513c898fe1B2d0E78d3b0e0A4a151589B1cBa
VITE_UNIVERSAL_ROUTER=${UNIVERSAL_ROUTER}
VITE_DONATION_WALLET=${DONATION}
VITE_MARKETING_WALLET=${MARKETING}
VITE_POOL_FEE=${POOL_FEE}
VITE_LP_TICK_LOWER=-887220
VITE_LP_TICK_UPPER=887220
VITE_RPC_URL=${FORK_RPC_URL}
VITE_CHAIN_ID=${FORK_CHAIN_ID}
VITE_HOOK_MODE=${HOOK_MODE}
EOF
  echo "Wrote $WEB_OUT"
fi
