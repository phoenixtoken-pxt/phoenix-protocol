#!/usr/bin/env bash
# Sync web/.env from evm/.env.anvil (or given env file).
# Usage: write-web-env.sh <evm-env-file> <web-env-out>
set -euo pipefail

EVM_ENV="${1:?usage: write-web-env.sh <evm-env-file> <web-env-out>}"
WEB_OUT="${2:?missing web env output path}"

# shellcheck disable=SC1090
set -a && . "$EVM_ENV" && set +a

POOL_MANAGER="${POOL_MANAGER:-0x05E73354cFDd6745C338b50BcFDfA3Aa6fA03408}"
POOL_SWAP_TEST="${POOL_SWAP_TEST:-0x8B5bcC363ddE2614281aD875bad385E0A785D3B9}"
ANVIL_RPC_URL="${ANVIL_RPC_URL:-http://127.0.0.1:8545}"
# Prefer PHOENIX_HOOK; fall back to legacy PHOENIX_V4_HOOK if present.
PHOENIX_HOOK="${PHOENIX_HOOK:-${PHOENIX_V4_HOOK:-}}"

mkdir -p "$(dirname "$WEB_OUT")"

cat >"$WEB_OUT" <<EOF
# Synced from ${EVM_ENV}
VITE_PXT_ADDRESS=${PXT_ADDRESS}
VITE_QUOTE_TOKEN_ADDRESS=${QUOTE_TOKEN_ADDRESS}
VITE_PHOENIX_HOOK=${PHOENIX_HOOK}
VITE_FEE_COLLECTOR=${FEE_COLLECTOR:-}
VITE_ANTI_BOT_OPEN_SELL=${ANTI_BOT_OPEN_SELL:-}
VITE_POOL_MANAGER=${POOL_MANAGER}
VITE_POOL_SWAP_TEST=${POOL_SWAP_TEST}
VITE_POOL_MODIFY_LIQUIDITY_TEST=${POOL_MODIFY_LIQUIDITY_TEST:-0x37429cD17Cb1454C34E7F50b09725202Fd533039}
VITE_STATE_VIEW=${STATE_VIEW:-0x571291b572ed32ce6751a2Cb2486EbEe8DEfB9B4}
VITE_QUOTER=${QUOTER:-0x4A6513c898fe1B2d0E78d3b0e0A4a151589B1cBa}
VITE_DONATION_WALLET=${DONATION_WALLET}
VITE_MARKETING_WALLET=${MARKETING_WALLET}
VITE_POOL_FEE=${POOL_FEE:-0}
VITE_LP_TICK_LOWER=${LP_TICK_LOWER:--887220}
VITE_LP_TICK_UPPER=${LP_TICK_UPPER:-887220}
VITE_RPC_URL=${ANVIL_RPC_URL}
VITE_CHAIN_ID=84532
VITE_EXPLORER_URL=${EXPLORER_URL:-http://127.0.0.1:5100}
VITE_HOOK_MODE=${HOOK_MODE:-return-delta}
EOF

echo "Wrote $WEB_OUT"
